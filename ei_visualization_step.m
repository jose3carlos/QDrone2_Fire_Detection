function [box,detected,confidence,resultID]=ei_visualization_step(image,index,total,batchID)
% Host-only entry called extrinsically by the optional Simulink block.
% Native [x y width height] uses zero-based coordinates; confidence is [0,1].
assert(isa(image,'uint8') && isreal(image) && isequal(size(image),[180 180]), ...
    'EI:VisualizationImage','Expected an unchanged uint8 180-by-180 grayscale image.');
assert(isscalar(index) && isscalar(total) && index>=1 && index<=total && ...
    index==floor(double(index)) && total==floor(double(total)) && ...
    isa(batchID,'uint64') && isscalar(batchID) && batchID>=1, ...
    'EI:VisualizationIndex','Invalid batch/image index.');
root=fileparts(mfilename('fullpath'));
file=fullfile(root,'build','visualization','active_visualization.mat');
assert(isfile(file),'EI:VisualizationSetup','Run setup_fomo_visualization before simulation.');
data=load(file,'visualization'); v=data.visualization;
data=load(fullfile(root,'build','active_model.mat'),'artifact'); a=data.artifact;
assert(strcmpi(v.projectRoot,root) && strcmpi(a.projectRoot,root) && ...
    strcmp(v.nativeKey,a.key) && strcmp(v.matlabVersion,version) && ...
    strcmp(v.host,getenv('COMPUTERNAME')) && isfile(v.binary) && isfile(a.dll), ...
    'EI:VisualizationSetup', ...
    'Visualization belongs to a different model/location/computer. Stop and run setup_fomo_visualization.');
addpath(v.folder);
result=feval(v.gateway,'infer',a.dll,image);
box=result.boundingBox; detected=logical(result.detected);
confidence=single(result.confidence/100); resultID=result.resultID;
ei_show_fomo_frame(image,result,index,total,batchID);
end
