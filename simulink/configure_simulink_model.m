function configure_simulink_model(model)
% Simulation target custom code: coder.ceval links the DLL import library.
cfg=config(); data=load(fullfile(cfg.buildRoot,'active_model.mat'),'artifact'); a=data.artifact;
setenv('PATH',[fileparts(a.dll) pathsep getenv('PATH')]);
set_param(model,'SimTargetLang','C++', ...
    'SimCustomHeaderCode',sprintf('#include "ei_wrapper.h"\n#include "mex.h"'), ...
    'SimUserIncludeDirs',['"' a.includeDir '"'], ...
    'SimUserLibraries',['"' a.importLibrary '"'], ...
    'SimCustomInitializer',sprintf(['{ int32_t s=ei_sim_start(%.9ef,%du,%du,%du,%.17g); ' ...
        'if(s<0) { char e[1024]; ei_get_last_error(e,1024); mexErrMsgIdAndTxt("EI:SimInit","%%s",e); } }'], ...
        cfg.minConfidence,a.falseIndex,cfg.maxDetections,cfg.debugLog,cfg.timeoutMs), ...
    'SimCustomTerminator','ei_sim_stop();');
set_param(model,'SolverType','Fixed-step','Solver','FixedStepDiscrete', ...
    'FixedStep',num2str(cfg.image.sampleTime,17),'SimulationMode','normal', ...
    'FastRestart','off','StartTime','0', ...
    'InitFcn',sprintf('ei_sim_prepare(''%s'');',model));
workspace=get_param(model,'ModelWorkspace');
assignin(workspace,'eiBuildInfo',struct('buildKey',a.key,'height',a.metadata.height,'width',a.metadata.width));
end
