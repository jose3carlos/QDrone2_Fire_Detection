function R = qd2_prueba_simulink(t_final, conservar)
%QD2_PRUEBA_SIMULINK Prueba de compatibilidad con Simulink / codegen.
%   R = qd2_prueba_simulink(t_final) construye de forma programática un
%   modelo desechable (en tempdir) con bloques MATLAB Function que llaman a
%   qd2_mission_step, qd2_separation_guard, qd2_mpc_position,
%   qd2_quad_plant, qd2_downwash y qd2_telemetry_pack (misión en versión
%   1 y 2, guard con 5 y 7 argumentos y ctx de 4 y 6, telemetría con 11 y
%   12 argumentos, este último con la actitud de y(61:63)), cierra el lazo con
%   Unit Delay y ejecuta sim(). Simulink compila el código de los bloques
%   MATLAB Function con su generador de código, así que cualquier
%   construcción incompatible con codegen (tamaños variables, cell arrays,
%   strings, etc.) hace fallar la prueba.
%   R : struct con el resultado (estados alcanzados, distancias, tiempos).
%   conservar = true deja el .slx en R.archivo para inspeccionarlo.

if nargin < 1, t_final = 40; end
if nargin < 2, conservar = false; end
lib = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(lib, 'lib'));

mdl = 'qd2_harness_tmp';
dir_tmp = fullfile(tempdir, ['qd2_harness_' char(java.util.UUID.randomUUID)]);
mkdir(dir_tmp);
viejo = cd(dir_tmp);
limpiar = onCleanup(@() terminar(mdl, viejo, dir_tmp, conservar));
if bdIsLoaded(mdl), close_system(mdl, 0); end
new_system(mdl);
set_param(mdl, 'SolverType', 'Fixed-step', 'Solver', 'FixedStepDiscrete', ...
    'FixedStep', '0.02', 'StopTime', num2str(t_final), 'SaveOutput', 'off', ...
    'SaveTime', 'off', 'SignalLogging', 'off', 'ReturnWorkspaceOutputs', 'on');

% ---------------- Código de los bloques -----------------------------------
c_mision = sprintf([ ...
 'function [spE, spR, ctx, est, eid, tel64, est2] = fcn(t, pos1, pos2, guard_act)\n' ...
 '%%#codegen\n' ...
 'persistent s s2 p\n' ...
 'if isempty(p)\n' ...
 '    p = qd2_params();\n' ...
 '    s = qd2_mission_init(p);\n' ...
 '    s2 = qd2_mission_init(p);\n' ...
 'end\n' ...
 'py = zeros(32,1);\n' ...
 'py(1) = floor(t/0.05);           %% heartbeat\n' ...
 'if t >= 3, py(2) = 1; py(3) = 1; end   %% START\n' ...
 'py(4) = 1;\n' ...
 'py(5:9) = [1; 1; 0.0; 1.2; 0.9];  %% objetivo sobre la N\n' ...
 'in.t = t;\n' ...
 'in.pose1 = [pos1(1:3); 0];\n' ...
 'in.pose2 = [pos2(1:3); 0];\n' ...
 'in.tracked1 = 1;\n' ...
 'in.tracked2 = 1;\n' ...
 'in.py = py;\n' ...
 'in.version = 1 + double(t < -1);   %% = 1, como valor de tiempo de ejecución\n' ...
 '[s, spE, spR, tel] = qd2_mission_step(s, in, p);\n' ...
 '%% misma entrada con la versión MPC (rama version = 2 compilada y ejecutada)\n' ...
 'in2 = in;\n' ...
 'in2.version = 1 + double(t >= 0);  %% = 2\n' ...
 'in2.py(21) = 0.6;                   %% override de z_R\n' ...
 '[s2, ~, ~, tel2] = qd2_mission_step(s2, in2, p);\n' ...
 '%% versión MPC con la FSM a bordo (qd2_enlace_mpc): el dron 2 entra a Error a los 30 s\n' ...
 'persistent s3 tm\n' ...
 'if isempty(s3)\n' ...
 '    s3 = qd2_mission_init(p);\n' ...
 '    tm = [-1 -1 0 0];\n' ...
 'end\n' ...
 'y8a = [t 5 16 0 14 0 0 2];\n' ...
 'y8b = y8a;\n' ...
 'if t > 30, y8b(2) = 7; end\n' ...
 '[ab, tm] = qd2_enlace_mpc(tm, t, y8a, y8b, [0 0], [0 0], p, in2.version);\n' ...
 'in3.t = t; in3.pose1 = in.pose1; in3.pose2 = in.pose2;\n' ...
 'in3.tracked1 = 1; in3.tracked2 = 1; in3.py = py; in3.version = in2.version;\n' ...
 'in3.fsm_a_bordo = ab(1:2); in3.proto_mal = ab(3:4);\n' ...
 '[s3, ~, ~, tel3] = qd2_mission_step(s3, in3, p);\n' ...
 '%% firma de 12 argumentos (actitud [roll1 pitch1 roll2 pitch2] -> y(61:63))\n' ...
 'y3 = qd2_telemetry_pack(t, tel3, 2, 0, in.pose1, in.pose2, tel3.sp1, tel3.sp2, [0 0 0], [0 0 0], [1 1 5 5 16 16 1 1], [0.01 -0.02 0.03 -0.04]);\n' ...
 'est2 = tel2.mission_state + 0*tel2.z_E + 0*y3(55) + 0*y3(63) + 0*tel3.escape(1);\n' ...
 'ctx = tel.ctx_guard;\n' ...
 'est = tel.mission_state;\n' ...
 'eid = tel.explorer_id;\n' ...
 'aux = [1 1 5 5 15.5 15.5 1 1];\n' ...
 'tel64 = qd2_telemetry_pack(t, tel, 1, guard_act, [pos1(1:3); 0], [pos2(1:3); 0], tel.sp1, tel.sp2, pos1(4:6), pos2(4:6), aux);\n']);

c_guard = sprintf([ ...
 'function [spE_o, spR_o, act] = fcn(pos1, pos2, spE, spR, ctx, eid)\n' ...
 '%%#codegen\n' ...
 'persistent gs p\n' ...
 'if isempty(p)\n' ...
 '    p = qd2_params();\n' ...
 '    gs = qd2_guard_init();\n' ...
 'end\n' ...
 'if eid == 2\n' ...
 '    pE = pos2(1:3); pR = pos1(1:3);\n' ...
 'else\n' ...
 '    pE = pos1(1:3); pR = pos2(1:3);\n' ...
 'end\n' ...
 '[spE_o, spR_o, act, gs] = qd2_separation_guard(pE, pR, spE, spR, p, gs, ctx);\n' ...
 '%% firmas alternativas: 5 argumentos y ctx de 4 elementos\n' ...
 '[a1, ~, act5] = qd2_separation_guard(pE, pR, spE, spR, p);\n' ...
 '[~, a2, act4] = qd2_separation_guard(pE, pR, spE, spR, p, gs, ctx(1:4));\n' ...
 'if ~all(isfinite([a1 a2 act5 act4])), act = NaN; end\n']);

c_mpc = sprintf([ ...
 'function [u, res] = fcn(xe, ref, other)\n' ...
 '%%#codegen\n' ...
 'persistent mst p\n' ...
 'if isempty(p)\n' ...
 '    p = qd2_params();\n' ...
 '    mst = qd2_mpc_init(p);\n' ...
 'end\n' ...
 '[u, mst, info] = qd2_mpc_position(xe, ref, other, p, mst);\n' ...
 'res = max(info.res);\n']);

c_planta = sprintf([ ...
 'function y = fcn(u, other, x0)\n' ...
 '%%#codegen\n' ...
 'persistent x p\n' ...
 'if isempty(p)\n' ...
 '    p = qd2_params();\n' ...
 '    x = zeros(10,1);\n' ...
 '    x(1:3) = x0;\n' ...
 '    x(10) = p.T_trim;\n' ...
 'end\n' ...
 '[F, sg] = qd2_downwash(x(1:3), other(1:3), p.dw);\n' ...
 'x = qd2_quad_plant(x, u(1:4), F, 0.02, p.planta);\n' ...
 'y = [x(1:6); x(7:9)];\n']);

c_ref = sprintf([ ...
 'function [ref1, ref2] = fcn(spE, spR, eid, t)\n' ...
 '%%#codegen\n' ...
 '%% Consigna por dron + prueba de qd2_track_waypoints/qd2_assign_roles\n' ...
 'persistent r1 r2\n' ...
 'if isempty(r1), r1 = [-1; 0; 1; 0]; r2 = [1; -0.3; 0.5; 0]; end\n' ...
 'if eid == 2, a = spR; b = spE; else, a = spE; b = spR; end\n' ...
 'rate = [1/3; 1/3; 1/6; pi/6];\n' ...
 'if a(3) > 0.2, r1 = qd2_rate_limit(r1, a(:), rate, 0.02, 1); end\n' ...
 'if b(3) > 0.2, r2 = qd2_rate_limit(r2, b(:), rate, 0.02, 1); end\n' ...
 '[wp, n] = qd2_track_waypoints([-1.2 1.2; 1.2 1.2; -1.2 -1.2; 1.2 -1.2], 0.25, 1.5);\n' ...
 '[e, r, h1, h2, ok] = qd2_assign_roles([-1 0], [1 0], 1, 1);\n' ...
 'ref1 = r1; ref2 = r2;\n' ...
 'if n < 2 || e ~= 1 || ok < 0.5 || wp(1,3) ~= 1.5, ref1(:) = NaN; end\n']);

c_onboard = sprintf([ ...
 'function [pos, fsm] = fcn(t)\n' ...
 '%%#codegen\n' ...
 '%% Tercer dron: emulación a bordo (qd2_onboard_step, PID y luego MPC)\n' ...
 'persistent ob x p\n' ...
 'if isempty(p)\n' ...
 '    p = qd2_params();\n' ...
 '    ob = qd2_onboard_init(p);\n' ...
 '    x = zeros(10,1); x(1:2) = [0; 1.3];\n' ...
 'end\n' ...
 'modo = 1; if t > 30, modo = 2; end\n' ...
 'xe = [x(1:6); x(7:9)];\n' ...
 '[u, ob] = qd2_onboard_step(ob, double(t > 1), double(t > 3), [0.3 1.3 1.0 0], xe, nan(6,1), p, 0.02, modo);\n' ...
 'x = qd2_quad_plant(x, u, zeros(3,1), 0.02, p.planta);\n' ...
 'pos = x(1:3);\n' ...
 'fsm = ob.fsm;\n']);

% ---------------- Bloques ---------------------------------------------------
add_block('simulink/Sources/Clock', [mdl '/Clock'], 'Position', [30 40 60 70]);
nombres = {'MISION', 'GUARD', 'REF', 'MPC1', 'MPC2', 'PLANTA1', 'PLANTA2', 'ONBOARD3'};
codigos = {c_mision, c_guard, c_ref, c_mpc, c_mpc, c_planta, c_planta, c_onboard};
pos = [150 30 330 170; 420 30 600 170; 690 30 870 150; 960 30 1140 110; ...
       960 160 1140 240; 1230 30 1410 110; 1230 160 1410 240; 420 380 600 450];
for i = 1:numel(nombres)
    b = [mdl '/' nombres{i}];
    add_block('simulink/User-Defined Functions/MATLAB Function', b, 'Position', pos(i,:));
    cfg = get_param(b, 'MATLABFunctionConfiguration');
    cfg.FunctionScript = codigos{i};
end
% Tamaños explícitos de las salidas (como haría un modelo real)
tam = struct('MISION', {{'spE','[1 4]';'spR','[1 4]';'ctx','[1 6]';'est','1';'eid','1';'tel64','[64 1]';'est2','1'}}, ...
    'GUARD', {{'spE_o','[1 4]';'spR_o','[1 4]';'act','1'}}, ...
    'REF', {{'ref1','[4 1]';'ref2','[4 1]'}}, ...
    'MPC1', {{'u','[5 1]';'res','1'}}, 'MPC2', {{'u','[5 1]';'res','1'}}, ...
    'PLANTA1', {{'y','[9 1]'}}, 'PLANTA2', {{'y','[9 1]'}}, ...
    'ONBOARD3', {{'pos','[3 1]';'fsm','1'}});
rt = sfroot;
for i = 1:numel(nombres)
    ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', [mdl '/' nombres{i}]);
    lista = tam.(nombres{i});
    for j = 1:size(lista, 1)
        dd = ch.find('-isa', 'Stateflow.Data', 'Name', lista{j,1});
        dd.Props.Array.Size = lista{j,2};
    end
end
% Unit Delay de las salidas de planta (rompen el lazo algebraico)
add_block('simulink/Discrete/Unit Delay', [mdl '/Z1'], 'Position', [1480 50 1520 90], ...
    'InitialCondition', '[-1;0;0;0;0;0;0;0;0]', 'SampleTime', '0.02');
add_block('simulink/Discrete/Unit Delay', [mdl '/Z2'], 'Position', [1480 180 1520 220], ...
    'InitialCondition', '[1;-0.3;0;0;0;0;0;0;0]', 'SampleTime', '0.02');
add_block('simulink/Discrete/Unit Delay', [mdl '/ZG'], 'Position', [620 200 660 240], ...
    'InitialCondition', '0', 'SampleTime', '0.02');
add_block('simulink/Sources/Constant', [mdl '/X01'], 'Value', '[-1;0;0]', 'Position', [1150 260 1190 280]);
add_block('simulink/Sources/Constant', [mdl '/X02'], 'Value', '[1;-0.3;0]', 'Position', [1150 300 1190 320]);
add_block('simulink/Sinks/To Workspace', [mdl '/LOG_POS1'], 'VariableName', 'pos1', 'SaveFormat', 'Array', 'Position', [1600 50 1660 80]);
add_block('simulink/Sinks/To Workspace', [mdl '/LOG_POS2'], 'VariableName', 'pos2', 'SaveFormat', 'Array', 'Position', [1600 180 1660 210]);
add_block('simulink/Sinks/To Workspace', [mdl '/LOG_EST'], 'VariableName', 'est', 'SaveFormat', 'Array', 'Position', [420 260 480 290]);
add_block('simulink/Sinks/To Workspace', [mdl '/LOG_EST2'], 'VariableName', 'est2', 'SaveFormat', 'Array', 'Position', [420 340 480 370]);
add_block('simulink/Sinks/To Workspace', [mdl '/LOG_ACT'], 'VariableName', 'act', 'SaveFormat', 'Array', 'Position', [690 200 750 230]);
add_block('simulink/Sinks/To Workspace', [mdl '/LOG_TEL'], 'VariableName', 'tel64', 'SaveFormat', 'Array', 'Position', [420 300 480 330]);
add_block('simulink/Sinks/To Workspace', [mdl '/LOG_RES'], 'VariableName', 'res', 'SaveFormat', 'Array', 'Position', [1230 300 1290 330]);
add_block('simulink/Sinks/To Workspace', [mdl '/LOG_U1'], 'VariableName', 'u1', 'SaveFormat', 'Array', 'Position', [1230 340 1290 370]);
add_block('simulink/Sinks/Terminator', [mdl '/T1'], 'Position', [1230 380 1250 400]);

% ---------------- Conexiones ----------------------------------------------
L = @(a, b) add_line(mdl, a, b, 'autorouting', 'on');
L('Clock/1', 'MISION/1');
L('Z1/1', 'MISION/2');
L('Z2/1', 'MISION/3');
L('ZG/1', 'MISION/4');
L('Z1/1', 'GUARD/1');
L('Z2/1', 'GUARD/2');
L('MISION/1', 'GUARD/3');
L('MISION/2', 'GUARD/4');
L('MISION/3', 'GUARD/5');
L('MISION/5', 'GUARD/6');
L('GUARD/3', 'ZG/1');
L('GUARD/1', 'REF/1');
L('GUARD/2', 'REF/2');
L('MISION/5', 'REF/3');
L('Clock/1', 'REF/4');
L('MISION/4', 'LOG_EST/1');
L('MISION/6', 'LOG_TEL/1');
L('MISION/7', 'LOG_EST2/1');
L('GUARD/3', 'LOG_ACT/1');
L('Z1/1', 'MPC1/1');
L('REF/1', 'MPC1/2');
L('Z2/1', 'MPC2/1');
L('REF/2', 'MPC2/2');
% "other" del MPC = pos/vel del otro dron (6 primeros estados)
add_block('simulink/Signal Routing/Selector', [mdl '/S1'], 'IndexOptions', 'Index vector (dialog)', ...
    'Indices', '[1 2 3 4 5 6]', 'InputPortWidth', '9', 'Position', [880 200 910 230]);
add_block('simulink/Signal Routing/Selector', [mdl '/S2'], 'IndexOptions', 'Index vector (dialog)', ...
    'Indices', '[1 2 3 4 5 6]', 'InputPortWidth', '9', 'Position', [880 250 910 280]);
L('Z2/1', 'S1/1');
L('Z1/1', 'S2/1');
L('S1/1', 'MPC1/3');
L('S2/1', 'MPC2/3');
L('MPC1/1', 'PLANTA1/1');
L('MPC2/1', 'PLANTA2/1');
L('S1/1', 'PLANTA1/2');
L('S2/1', 'PLANTA2/2');
L('X01/1', 'PLANTA1/3');
L('X02/1', 'PLANTA2/3');
L('PLANTA1/1', 'Z1/1');
L('PLANTA2/1', 'Z2/1');
L('Z1/1', 'LOG_POS1/1');
L('Z2/1', 'LOG_POS2/1');
L('MPC1/2', 'LOG_RES/1');
L('MPC1/1', 'LOG_U1/1');
L('MPC2/2', 'T1/1');
add_block('simulink/Sinks/To Workspace', [mdl '/LOG_POS3'], 'VariableName', 'pos3', 'SaveFormat', 'Array', 'Position', [690 380 750 410]);
add_block('simulink/Sinks/To Workspace', [mdl '/LOG_FSM3'], 'VariableName', 'fsm3', 'SaveFormat', 'Array', 'Position', [690 420 750 450]);
L('Clock/1', 'ONBOARD3/1');
L('ONBOARD3/1', 'LOG_POS3/1');
L('ONBOARD3/2', 'LOG_FSM3/1');

save_system(mdl, fullfile(dir_tmp, [mdl '.slx']));
t0 = tic;
out = sim(mdl);
R.t_sim_reloj = toc(t0);
R.pos1 = a_filas(out.get('pos1'));
R.pos2 = a_filas(out.get('pos2'));
R.est = a_filas(out.get('est'));
R.tel64 = a_filas(out.get('tel64'));
R.res = a_filas(out.get('res'));
R.u1 = a_filas(out.get('u1'));
R.pos3 = a_filas(out.get('pos3'));
R.fsm3 = a_filas(out.get('fsm3'));
R.est2 = a_filas(out.get('est2'));
R.act = a_filas(out.get('act'));
R.estados = unique(R.est(:))';
R.estados2 = unique(R.est2(:))';
d = sqrt((R.pos1(:,1) - R.pos2(:,1)).^2 + (R.pos1(:,2) - R.pos2(:,2)).^2);
R.dh_min = min(d);
R.archivo = fullfile(dir_tmp, [mdl '.slx']);
R.ok = all(isfinite(R.pos1(:))) && all(isfinite(R.pos2(:))) && all(isfinite(R.act(:)));
end

function A = a_filas(A)
% To Workspace guarda vectores columna como ancho x 1 x N: pasar a N x ancho.
if ndims(A) == 3
    A = permute(A, [3 1 2]);
end
end

function terminar(mdl, viejo, dir_tmp, conservar)
if bdIsLoaded(mdl), close_system(mdl, 0); end
cd(viejo);
if ~conservar
    try
        rmdir(dir_tmp, 's');
    catch
    end
end
end
