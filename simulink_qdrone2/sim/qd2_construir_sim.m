function s = codigo_detector()
s = sprintf([ ...
'function tg = fcn(x1, x2, tel, ur, nr, QD2_SIM)\n' ...
'%%#codegen\n' ...
'%% DETECTOR SIMULADO: cámara cenital del EXPLORADOR (RealSense mirando abajo).\n' ...
'%% Huella = rectángulo de semiancho z*tan(vfov/2) (eje x del dron) por\n' ...
'%% z*tan(hfov/2) (eje y), centrado en la cámara (offset del soporte).\n' ...
'%% Cada objetivo dentro de la huella cuenta una observación por frame\n' ...
'%% (~12.5 fps) con probabilidad det_p; con det_frames observaciones se\n' ...
'%% publica como lo haría la estación Python: [id clase x y confianza].\n' ...
'%% Salida tg = [n_targets; 3 ranuras x 5] (índices 4-19 del paquete de 32),\n' ...
'%% rotando las ranuras entre todos los publicados.\n' ...
'persistent obs pub npub k rot\n' ...
'if isempty(obs)\n' ...
'    obs = zeros(16, 1);\n' ...
'    pub = zeros(16, 5);\n' ...
'    npub = 0;\n' ...
'    k = 0;\n' ...
'    rot = 0;\n' ...
'end\n' ...
'k = k + 1;\n' ...
'O = QD2_SIM.objetivos_tabla;\n' ...
'eid = tel(4);\n' ...
'estado = tel(2);\n' ...
'if mod(k, 4) == 0 && (eid == 1 || eid == 2) && estado >= 4 && estado <= 6\n' ...
'    if eid == 1\n' ...
'        xe = x1;\n' ...
'    else\n' ...
'        xe = x2;\n' ...
'    end\n' ...
'    z = xe(3);\n' ...
'    if z >= QD2_SIM.det_z_min\n' ...
'        c = cos(xe(9)); s = sin(xe(9));\n' ...
'        cx = xe(1) + c*QD2_SIM.det_offset(1) - s*QD2_SIM.det_offset(2);\n' ...
'        cy = xe(2) + s*QD2_SIM.det_offset(1) + c*QD2_SIM.det_offset(2);\n' ...
'        hx = z*tan(QD2_SIM.det_vfov*pi/360);\n' ...
'        hy = z*tan(QD2_SIM.det_hfov*pi/360);\n' ...
'        for j = 1:16\n' ...
'            if isfinite(O(j,1)) && obs(j) < QD2_SIM.det_frames\n' ...
'                dx = O(j,1) - cx; dy = O(j,2) - cy;\n' ...
'                bx = c*dx + s*dy; by = -s*dx + c*dy;\n' ...
'                if abs(bx) <= hx && abs(by) <= hy && ur(j) < QD2_SIM.det_p\n' ...
'                    obs(j) = obs(j) + 1;\n' ...
'                    if obs(j) >= QD2_SIM.det_frames && npub < 16\n' ...
'                        npub = npub + 1;\n' ...
'                        pub(npub, :) = [npub, O(j,3), O(j,1) + QD2_SIM.det_ruido*nr(1), ...\n' ...
'                                        O(j,2) + QD2_SIM.det_ruido*nr(2), 0.85];\n' ...
'                    end\n' ...
'                end\n' ...
'            end\n' ...
'        end\n' ...
'    end\n' ...
'end\n' ...
'tg = zeros(16, 1);\n' ...
'tg(1) = npub;\n' ...
'if npub > 0\n' ...
'    rot = rot + 1;\n' ...
'    for r = 1:3\n' ...
'        q = mod(rot*3 + r - 1, npub) + 1;\n' ...
'        tg(2 + 5*(r-1) : 6 + 5*(r-1)) = pub(q, :)'';\n' ...
'    end\n' ...
'end\n']);
end

