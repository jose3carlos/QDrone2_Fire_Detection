function s = codigo_onboard(i)
s = sprintf([ ...
'function [u, st] = fcn(trig, des, mpcx, x, version, dpose, t, QD2P, QD2_SIM)\n' ...
'%%#codegen\n' ...
'%% STACK A BORDO SIMULADO del QDrone 2 #%d (500 Hz): FSM + PIV original o MPC\n' ...
'%% (qd2_onboard_step), con la estimación y los errores del stack real.\n' ...
'%% trig = [arm takeoff estop 0], des = pose deseada [x y z yaw],\n' ...
'%% mpcx = [otro dron x y z vx vy vz, mpc_mode, 0] (índices 17-24 del paquete MPC),\n' ...
'%% x = estado verdadero de la planta (solo para la IMU: roll, pitch, aceleración),\n' ...
'%% dpose = OptiTrack [x y z roll pitch yaw isTracking] (100 Hz, NaN sin rastreo).\n' ...
'ID = %d;\n' ...
'NB = 64;\n' ...
'persistent ob bat buf kb pos vf1 vf2 vest vprev pprev t_trk t_com paq T7 u_prev fh t_ap\n' ...
'dt = 0.002;\n' ...
'if isempty(ob)\n' ...
'    ob = qd2_onboard_init(QD2P);\n' ...
'    bat = 16.4;\n' ...
'    buf = zeros(7, NB);\n' ...
'    for j = 1:NB\n' ...
'        buf(:, j) = [x(1); x(2); x(3); x(7); x(8); x(9); 1];\n' ...
'    end\n' ...
'    kb = 1;\n' ...
'    pos = [x(1); x(2); x(3); x(9)];\n' ...
'    pprev = pos(1:3);\n' ...
'    vf1 = zeros(3, 1); vf2 = zeros(3, 1); vest = zeros(3, 1);\n' ...
'    vprev = [x(4); x(5); x(6)];\n' ...
'    t_trk = 0; t_com = 0; T7 = 0;\n' ...
'    paq = [trig(:); des(:); mpcx(:); dpose(:)];\n' ...
'    u_prev = zeros(4, 1);\n' ...
'    fh = false; t_ap = 0;\n' ...
'end\n' ...
'%% ---- enlace PC -> dron: pérdidas programadas QD2_SIM.comm_off [dron t1 t2] ----\n' ...
'sin_enlace = false;\n' ...
'co = QD2_SIM.comm_off;\n' ...
'for k = 1:size(co, 1)\n' ...
'    if co(k,1) == ID && t >= co(k,2) && t < co(k,3)\n' ...
'        sin_enlace = true;\n' ...
'    end\n' ...
'end\n' ...
'if ~sin_enlace\n' ...
'    paq = [trig(:); des(:); mpcx(:); dpose(:)];   %% "most recent": sin enlace queda el último\n' ...
'    t_com = 0;\n' ...
'else\n' ...
'    t_com = t_com + dt;\n' ...
'end\n' ...
'tr = paq(1:4); ds = paq(5:8); mx = paq(9:16); dp = paq(17:23);\n' ...
'%% ---- estimación a bordo ------------------------------------------------\n' ...
'%% pose OptiTrack con latencia (buffer circular a 500 Hz)\n' ...
'buf(:, kb) = dp;\n' ...
'nl = min(max(round(QD2_SIM.lat_pose/dt), 0), NB - 1);\n' ...
'j = kb - nl;\n' ...
'if j < 1, j = j + NB; end\n' ...
'dd = buf(:, j);\n' ...
'kb = kb + 1;\n' ...
'if kb > NB, kb = 1; end\n' ...
'trk = dd(7) > 0.5 && all(isfinite(dd(1:6)));\n' ...
'if trk\n' ...
'    pos = [dd(1); dd(2); dd(3); dd(6)];\n' ...
'end\n' ...
'if QD2_SIM.pose_onboard < 0.5\n' ...
'    pos = [x(1); x(2); x(3); x(9)];   %% estimación ideal (solo para comparar)\n' ...
'    trk = true;\n' ...
'end\n' ...
'%% velocidad: complementario acelerómetro + derivada de OptiTrack (LPF 2o orden\n' ...
'%% wn = 50 rad/s, zeta = 1; Kp3 = 4), como HORIZON FRAME CONVERSION AND ESTIMATION\n' ...
'dpos = (pos(1:3) - pprev)/dt;\n' ...
'pprev = pos(1:3);\n' ...
'a = 50*dt;\n' ...
'vf1 = vf1 + a*(dpos - vf1);\n' ...
'vf2 = vf2 + a*(vf1 - vf2);\n' ...
'acc = ([x(4); x(5); x(6)] - vprev)/dt;\n' ...
'vprev = [x(4); x(5); x(6)];\n' ...
'vest = vest + dt*(acc + 4*(vf2 - vest));\n' ...
'if QD2_SIM.pose_onboard < 0.5\n' ...
'    vest = [x(4); x(5); x(6)];\n' ...
'end\n' ...
'x_est = [pos(1); pos(2); pos(3); vest(1); vest(2); vest(3); x(7); x(8); pos(4)];\n' ...
'%% ---- errores del stack original (STATE MACHINE SIGNALS) ----------------\n' ...
'if ~trk && t > 1\n' ...
'    t_trk = t_trk + dt;\n' ...
'else\n' ...
'    t_trk = 0;\n' ...
'end\n' ...
'err_trk = t_trk >= 0.2;\n' ...
'err_com = t > 3 && t_com >= 0.5;\n' ...
'if (err_trk || err_com) && ob.fsm <= 6\n' ...
'    ob.fsm = 7;                %% Error -> EMERGENCY STOP (rampa)\n' ...
'    T7 = u_prev(1);\n' ...
'end\n' ...
'if t_com >= 1.0 && tr(1) > 0.5 && ob.fsm ~= 9\n' ...
'    ob.fsm = 9;                %% FLIGHT SAFETY: enlace perdido 1 s y armado -> corta motores\n' ...
'end\n' ...
'%% ---- falla a bordo programada (QD2_SIM.falla_fsm [dron t]) o al estar apilados\n' ...
'%% (QD2_SIM.falla_apilado: 1 = falla el de ARRIBA, 2 = el de ABAJO, tras 1 s con\n' ...
'%% dh < 0.15 m y dz > 0.5 m): Error -> estado 7 como el stack original\n' ...
'falla = false;\n' ...
'fa = QD2_SIM.falla_fsm;\n' ...
'for k = 1:size(fa, 1)\n' ...
'    if fa(k,1) == ID && fa(k,2) >= 0 && t >= fa(k,2)\n' ...
'        falla = true;\n' ...
'    end\n' ...
'end\n' ...
'if QD2_SIM.falla_apilado > 0.5 && all(isfinite(mx(1:3)))\n' ...
'    dz = x(3) - mx(3);\n' ...
'    apil = sqrt((x(1) - mx(1))^2 + (x(2) - mx(2))^2) < 0.15 && abs(dz) > 0.5 && min(x(3), mx(3)) > 0.2;\n' ...
'    yo_arriba = dz > 0;\n' ...
'    if apil && ((QD2_SIM.falla_apilado < 1.5 && yo_arriba) || (QD2_SIM.falla_apilado > 1.5 && ~yo_arriba))\n' ...
'        t_ap = t_ap + dt;\n' ...
'    else\n' ...
'        t_ap = 0;\n' ...
'    end\n' ...
'    if t_ap >= 1.0\n' ...
'        falla = true;\n' ...
'    end\n' ...
'end\n' ...
'if falla && ~fh && ob.fsm >= 1 && ob.fsm <= 6\n' ...
'    fh = true;\n' ...
'    ob.fsm = 7;\n' ...
'    T7 = u_prev(1);\n' ...
'end\n' ...
'if tr(3) > 0.5\n' ...
'    ob.fsm = 9;                %% E-stop: corte de motores (estado 8 -> 9 del original)\n' ...
'end\n' ...
'modo = 1;\n' ...
'if version > 1.5 && mx(7) > 0.5\n' ...
'    modo = 2;\n' ...
'end\n' ...
'otro = [mx(1); mx(2); mx(3); mx(4); mx(5); mx(6)];\n' ...
'ref = [ds(1) ds(2) ds(3) ds(4)];\n' ...
'if ob.fsm == 7\n' ...
'    %% actitud nivelada, sin control de posición, empuje baja a 1.75 N/s\n' ...
'    T7 = max(T7 - 1.75*dt, 0);\n' ...
'    u = [T7; 0; 0; 0];\n' ...
'    if T7 <= 7.38\n' ...
'        ob.fsm = 9;\n' ...
'        u = zeros(4, 1);\n' ...
'    end\n' ...
'else\n' ...
'    [u, ob] = qd2_onboard_step(ob, tr(1), tr(2), ref, x_est, otro, QD2P, dt, modo);\n' ...
'end\n' ...
'u_prev = u;\n' ...
'bat = bat - dt*3.2e-4*u(1);   %% descarga simple: ~0.005 V/s en hover\n' ...
'est = 3;\n' ...
'if ob.fsm >= 4 && ob.fsm <= 6\n' ...
'    if modo > 1.5\n' ...
'        est = ob.status;\n' ...
'    else\n' ...
'        est = 4;\n' ...
'    end\n' ...
'end\n' ...
'st = [ob.fsm; bat; est; u(1); double(err_com)];\n'], i, i);
end

