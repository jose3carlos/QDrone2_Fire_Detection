function s = codigo_estacion()
s = sprintf([ ...
'function py = fcn(t, tel, QD2P, QD2_SIM)\n' ...
'%%#codegen\n' ...
'%% ESTACIÓN SIMULADA (para correr sin la UI): heartbeat a 50 Hz, START en\n' ...
'%% QD2_SIM.t_start y LAND_ALL cuando los dos drones llevan t_land_espera s en\n' ...
'%% su home durante RETURN_HOME (si auto_land = false).\n' ...
'persistent hb seq cmd t_casa start_ok land_ok\n' ...
'if isempty(hb)\n' ...
'    hb = 0; seq = 0; cmd = 0; t_casa = -1; start_ok = 0; land_ok = 0;\n' ...
'end\n' ...
'hb = hb + 1;\n' ...
'estado = tel(2);\n' ...
'if start_ok < 0.5 && t >= QD2_SIM.t_start && estado == 2\n' ...
'    seq = seq + 1; cmd = 1; start_ok = 1;\n' ...
'end\n' ...
'en_casa = false;\n' ...
'if estado == 6\n' ...
'    d1 = hypot(tel(17) - tel(29), tel(18) - tel(30));\n' ...
'    d2 = hypot(tel(35) - tel(47), tel(36) - tel(48));\n' ...
'    en_casa = d1 < 0.15 && d2 < 0.15;\n' ...
'end\n' ...
'if en_casa\n' ...
'    if t_casa < 0, t_casa = t; end\n' ...
'else\n' ...
'    t_casa = -1;\n' ...
'end\n' ...
'if land_ok < 0.5 && QD2P.auto_land < 0.5 && t_casa >= 0 && t - t_casa >= QD2_SIM.t_land_espera\n' ...
'    seq = seq + 1; cmd = 3; land_ok = 1;\n' ...
'end\n' ...
'py = zeros(32, 1);\n' ...
'py(1) = hb;\n' ...
'py(2) = cmd;\n' ...
'py(3) = seq;\n']);
end

function s = codigo_merge()
s = sprintf([ ...
'function py = fcn(fuente, py_python, conectado, py_estacion, tg)\n' ...
'%%#codegen\n' ...
'%% COMMAND MERGE: elige la fuente de comandos y completa los objetivos.\n' ...
'if fuente > 1.5\n' ...
'    %% sin cliente queda el último paquete: el heartbeat deja de crecer\n' ...
'    %% (-> PAUSED en MISSION), igual que con el puente real\n' ...
'    py = py_python + 0*conectado;\n' ...
'else\n' ...
'    py = py_estacion;\n' ...
'end\n' ...
'%% Si la fuente no publica objetivos, los pone el detector simulado.\n' ...
'if py(4) < 0.5\n' ...
'    py(4) = tg(1);\n' ...
'    for i = 1:15\n' ...
'        py(4 + i) = tg(1 + i);\n' ...
'    end\n' ...
'end\n']);
end

