function info = qd2_construir_sim(raiz)
%QD2_CONSTRUIR_SIM Genera sim/QD2_Sim_Dual.slx (simulación SIL de los 2 drones).
%   info = qd2_construir_sim(raiz)   raiz = carpeta simulink_qdrone2.
%   Lo llama construir_dron_y_sim.m. Ver sim/README.md.
%
%   Estructura (todo a nivel raíz, conectado con Goto/From como el
%   MissionCtrl del Equipo2):
%     0. Configuración: VERSION (1 PID / 2 MPC) y COMMAND SOURCE
%        (1 estación simulada / 2 estación Python por :18700).
%     1. QDRONE 2 #1/#2 (SIM): FSM + PIV original o MPC a bordo
%        (qd2_onboard_step) + planta qd2_quad_plant a 500 Hz; DOWNWASH
%        COUPLING entre ambos (qd2_downwash + ruido).
%     2. OPTITRACK (SIM, 100 Hz): ruido, rastreo y pérdidas de rastreo.
%     3. Misión: bloques ENLAZADOS de lib/QD2_Mission_Lib.slx (ROLE & HOME
%        ASSIGNMENT, MISSION SUPERVISOR, SEPARATION GUARD, OPERATOR SAFETY
%        LAYER, SETPOINT RATE LIMITER, VELOCITY ESTIMATE, STACKING INFO,
%        TELEMETRY PACK), los mismos que usan los modelos de tierra.
%     4. PYTHON BRIDGE (Stream Server :18700 con sockets Java), estación y
%        detector simulados.
%     5. Scopes y registro (To Workspace) para las corridas sin interfaz.

mdl = 'QD2_Sim_Dual';
dir_sim = fullfile(raiz, 'sim');
archivo = fullfile(dir_sim, [mdl '.slx']);
addpath(fullfile(raiz, 'lib'));
addpath(dir_sim);
lib = 'QD2_Mission_Lib';
f_lib = fullfile(raiz, 'lib', [lib '.slx']);
% La librería la genera construir_modelos.m (otro script). Si justo se
% está regenerando, se espera un poco.
for k = 1:60
    if exist(f_lib, 'file'), break; end
    pause(2);
end
if ~exist(f_lib, 'file')
    error('qd2_construir_sim:sin_lib', ['No existe %s. Genérala primero con ' ...
        'construir_modelos(''verificar'', false, ''exportar'', false, ''capturas'', false).'], f_lib);
end
if bdIsLoaded(mdl), close_system(mdl, 0); end
if bdIsLoaded(lib), close_system(lib, 0); end
if exist(archivo, 'file'), delete(archivo); end   % evita el aviso de "shadowing"

load_system(f_lib);
evalin('base', 'QD2P = qd2_params_from_config(); QD2_SIM = qd2_sim_parametros(); QD2_VERSION = 1;');

new_system(mdl);
set_param(mdl, 'SolverType', 'Fixed-step', 'Solver', 'FixedStepDiscrete', 'FixedStep', '0.002', ...
    'StopTime', '400', 'SolverMode', 'SingleTasking', 'ReturnWorkspaceOutputs', 'on', ...
    'SaveTime', 'off', 'SaveOutput', 'off', 'SignalLogging', 'off', 'SaveState', 'off', ...
    'SaveFormat', 'Array', 'AlgebraicLoopMsg', 'error');
set_param(mdl, 'EnablePacing', 'on', 'PacingRate', 1);   % tiempo real (Simulation Pacing)
set_param(mdl, 'InitFcn', codigo_initfcn());
set_param(mdl, 'PreLoadFcn', codigo_preload());   % rutas ANTES de resolver los enlaces a QD2_Mission_Lib
set_param(mdl, 'PostLoadFcn', codigo_rutas());
set_param(mdl, 'ZoomFactor', '60');
% QUARC agrega sus logotipos a todo modelo nuevo: se acomodan junto al título
% (como en los modelos del Equipo2)
if getSimulinkBlockHandle([mdl '/Quanser']) > 0
    set_param([mdl '/Quanser'], 'Position', [2420 -215 2462 -170]);
end
if getSimulinkBlockHandle([mdl '/Powered by QUARC']) > 0
    set_param([mdl '/Powered by QUARC'], 'Position', [2480 -228 2688 -153]);
end

% ---------------- Encabezado ------------------------------------------------
nota(mdl, [40 -230 900 -60], sprintf([ ...
    'Group Description:\n\n' ...
    '0. Configuración: VERSION (1 = PID, 2 = MPC) y COMMAND SOURCE (1 = estación simulada, 2 = estación Python por tcpip://localhost:18700).\n' ...
    '1. Simulated QDrones: FSM a bordo + PIV original del Equipo2 o MPC a bordo, planta de cuadricóptero (500 Hz) y downwash entre drones.\n' ...
    '2. Localization: OptiTrack simulado (100 Hz, ruido, pérdidas de rastreo).\n' ...
    '3. Mission: bloques de QD2_Mission_Lib (los mismos de QD2_MissionCtrl_Dual_PID/MPC).\n' ...
    '4. Python Bridge: Stream Server :18700 (64 doubles a 50 Hz / 32 doubles), estación y detector simulados.\n' ...
    '5. Scopes y registro. Simulation Pacing activo (tiempo real); sim() sin interfaz lo apaga (qd2_correr_sim).']), 11, 'left');
nota(mdl, [2000 -200 2800 -110], sprintf('Quanser Autonomous Vehicles Research Studio\nQD2 Sim Dual (SIL) - 2x QDrone 2'), 18, 'right');

% ================ 0. Configuración =========================================
area(mdl, '0. Configuration', [40 0 730 200]);
add_block('simulink/Sources/Constant', [mdl '/VERSION'], 'Value', '1', 'Position', [90 40 150 70], ...
    'BackgroundColor', 'red', 'SampleTime', 'inf');
set_param([mdl '/VERSION'], 'Name', sprintf('VERSION\n(1 = PID, 2 = MPC)'));
blk_ver = [mdl '/' sprintf('VERSION\n(1 = PID, 2 = MPC)')];
goto_en(mdl, blk_ver, 1, 'VERSION');
add_block('simulink/Sources/Constant', [mdl '/SOURCE'], 'Value', '1', 'Position', [90 105 150 135], ...
    'BackgroundColor', 'orange', 'SampleTime', 'inf');
set_param([mdl '/SOURCE'], 'Name', sprintf('COMMAND SOURCE\n(1 = sim station, 2 = Python :18700)'));
blk_src = [mdl '/' sprintf('COMMAND SOURCE\n(1 = sim station, 2 = Python :18700)')];
goto_en(mdl, blk_src, 1, 'SOURCE');
add_block('simulink/Sources/Digital Clock', [mdl '/Clock'], 'SampleTime', '0.01', 'Position', [420 40 450 70]);
goto_en(mdl, [mdl '/Clock'], 1, 'T');
add_block('simulink/Logic and Bit Operations/Compare To Constant', [mdl '/is MPC'], ...
    'relop', '==', 'const', '2', 'Position', [470 105 520 135]);
add_block('simulink/Signal Attributes/Data Type Conversion', [mdl '/to double'], ...
    'OutDataTypeStr', 'double', 'Position', [545 110 575 130], 'ShowName', 'off');
add_line(mdl, 'is MPC/1', 'to double/1');
from_en(mdl, [mdl '/is MPC'], 1, 'VERSION');
goto_en(mdl, [mdl '/to double'], 1, 'MPC_MODE');
nota(mdl, [400 158 720 174], 'mpc_mode (índice 23) = 1 en la versión MPC', 9, 'left');
nota(mdl, [50 178 720 196], 'Por defecto SOURCE = 1 (corre sola). Para la UI web pon SOURCE = 2 antes de Run.', 9, 'left');

% ================ 1. Drones simulados ======================================
area(mdl, '1. Simulated QDrones (on-board stack + plant, 500 Hz)', [1950 0 2800 780]);
for i = 1:2
    b = [mdl sprintf('/QDRONE 2 #%d (SIM)', i)];
    crear_dron(b, i, [2200 40+300*(i-1) 2450 280+300*(i-1)]);
    tags_in = {sprintf('TRIG%d', i), sprintf('DES%d', i), sprintf('MPCX%d', i), sprintf('F%d', i), 'VERSION', sprintf('D%d', i)};
    for k = 1:numel(tags_in), from_en(mdl, b, k, tags_in{k}); end
    goto_en(mdl, b, 1, sprintf('X%d', i));
    goto_en(mdl, b, 2, sprintf('ST%d', i));
end
b = [mdl '/DOWNWASH COUPLING'];
crear_downwash(b, [2200 650 2450 730]);
from_en(mdl, b, 1, 'X1'); from_en(mdl, b, 2, 'X2');
goto_en(mdl, b, 1, 'F1'); goto_en(mdl, b, 2, 'F2');

% ================ 2. OptiTrack ==============================================
area(mdl, '2. Localization - OptiTrack (simulated, 100 Hz)', [40 220 700 420]);
b = [mdl '/OPTITRACK (SIM, 100 Hz)'];
crear_optitrack(b, [300 270 520 380]);
from_en(mdl, b, 1, 'X1'); from_en(mdl, b, 2, 'X2');
goto_en(mdl, b, 1, 'D1'); goto_en(mdl, b, 2, 'D2');

% ================ 3. Misión (QD2_Mission_Lib) ==============================
area(mdl, '3. Mission (QD2_Mission_Lib, 100 Hz)', [760 0 1900 1480]);
L = struct();
L.roles = lib_blk(mdl, lib, 'ROLE & HOME ASSIGNMENT', [900 40 1120 140], {'D1', 'D2'}, {'POSE1', 'POSE2', 'TRK', ''});
L.v1 = lib_blk(mdl, lib, 'VELOCITY ESTIMATE', [900 180 1120 230], {'T', 'D1'}, {'V1'}, 'VELOCITY ESTIMATE QDrone 1');
L.v2 = lib_blk(mdl, lib, 'VELOCITY ESTIMATE', [900 260 1120 310], {'T', 'D2'}, {'V2'}, 'VELOCITY ESTIMATE QDrone 2');
L.sup = lib_blk(mdl, lib, 'MISSION SUPERVISOR', [900 340 1120 580], {'T', 'POSE1', 'POSE2', 'TRK', 'PY', 'ONBOARD'}, ...
    {'SP1', 'SP2', 'CTX', 'INFO', 'MSTATE', 'CMD1', 'CMD2'});
L.guard = lib_blk(mdl, lib, 'SEPARATION GUARD', [900 610 1120 750], {'POSE1', 'POSE2', 'SP1', 'SP2', 'CTX'}, ...
    {'SP1G', 'SP2G', 'GUARD_RAW'});
b = [mdl '/SETPOINT SELECT (PID: GUARD, MPC: DIRECT)'];
crear_mf(b, [900 780 1120 950], codigo_select(), {'sp1', '[4 1]'; 'sp2', '[4 1]'; 'guard', '1'}, {}, '0.01');
tg = {'VERSION', 'SP1', 'SP2', 'SP1G', 'SP2G', 'GUARD_RAW'};
for k = 1:numel(tg), from_en(mdl, b, k, tg{k}); end
goto_en(mdl, b, 1, 'SP1S'); goto_en(mdl, b, 2, 'SP2S'); goto_en(mdl, b, 3, 'GUARD');
add_block('simulink/Sources/Constant', [mdl '/Operator Switches'], 'Value', '[1; 1; 0; 0]', ...
    'SampleTime', '0.01', 'Position', [930 1110 990 1130]);
set_param([mdl '/Operator Switches'], 'Name', sprintf('Operator Switches (sim)\n[Arm Takeoff EStop 0]'));
goto_en(mdl, [mdl '/' sprintf('Operator Switches (sim)\n[Arm Takeoff EStop 0]')], 1, 'SW');
add_block('simulink/Sources/Constant', [mdl '/Mission Mode'], 'Value', '0', ...
    'SampleTime', '0.01', 'Position', [930 1180 990 1200]);
set_param([mdl '/Mission Mode'], 'Name', sprintf('Command Source = MISSION (0)'));
goto_en(mdl, [mdl '/Command Source = MISSION (0)'], 1, 'OPMODE');
L.op = lib_blk(mdl, lib, 'OPERATOR SAFETY LAYER', [1450 140 1670 260], {'T', 'SW', 'CMD1', 'CMD2', 'OPMODE'}, ...
    {'TRIG1', 'TRIG2', ''});
L.rl1 = lib_blk(mdl, lib, 'SETPOINT RATE LIMITER', [1450 295 1670 375], {'T', 'SP1S', 'TRIG1', 'INFO'}, {'DES1'}, 'SETPOINT RATE LIMITER QDrone 1');
L.rl2 = lib_blk(mdl, lib, 'SETPOINT RATE LIMITER', [1450 400 1670 480], {'T', 'SP2S', 'TRIG2', 'INFO'}, {'DES2'}, 'SETPOINT RATE LIMITER QDrone 2');
L.stk = lib_blk(mdl, lib, 'STACKING INFO', [1450 520 1670 620], {'D1', 'D2', 'V1', 'V2', 'MPC_MODE'}, {'MPCX1', 'MPCX2', ''});
b = [mdl '/DRONE STATUS (sim link)'];
crear_mf(b, [900 975 1120 1085], codigo_status(), {'st', '[8 1]'}, {}, '0.01');
tg = {'ST1', 'ST2', 'VERSION', 'TRIG1', 'TRIG2'};
for k = 1:numel(tg), from_en(mdl, b, k, tg{k}); end
goto_en(mdl, b, 1, 'DSTATUS');
L.tel = lib_blk(mdl, lib, 'TELEMETRY PACK', [1450 680 1670 1000], ...
    {'T', 'INFO', 'GUARD', 'D1', 'D2', 'DES1', 'DES2', 'V1', 'V2', 'DSTATUS'}, {'TEL'});
% Respuesta de 8 doubles de cada dron (§3.2) a partir del estado a bordo
% simulado + MPC LINK CHECK (el mismo bloque del modelo de tierra MPC): la
% FSM a bordo llega al MISSION SUPERVISOR (falla a bordo -> alerta 9).
b = [mdl '/DRONE LINK (sim, 8 doubles)'];
crear_mf(b, [900 1260 1120 1420], codigo_link(), {'tel1', '[8 1]'; 'tel2', '[8 1]'; 'lb', '[2 1]'; 'cs', '[2 1]'}, ...
    {'QD2_SIM'}, '0.01');
from_en(mdl, b, 1, 'T'); from_en(mdl, b, 2, 'ST1'); from_en(mdl, b, 3, 'ST2');
goto_en(mdl, b, 1, 'TEL8_1'); goto_en(mdl, b, 2, 'TEL8_2'); goto_en(mdl, b, 3, 'LB'); goto_en(mdl, b, 4, 'CS');
add_block('simulink/Signal Routing/Demux', [mdl '/Demux LB'], 'Outputs', '2', 'ShowName', 'off', ...
    'Position', [1330 1105 1335 1145]);
add_block('simulink/Signal Routing/Demux', [mdl '/Demux CS'], 'Outputs', '2', 'ShowName', 'off', ...
    'Position', [1330 1175 1335 1215]);
L.enl = lib_blk(mdl, lib, 'MPC LINK CHECK', [1450 1060 1670 1240], ...
    {'T', 'TEL8_1', 'TEL8_2', '', '', '', ''}, {'ONBOARD_RAW'});
% 1 paso de retardo (como en el modelo de tierra): la respuesta del dron
% depende de los disparos que salen del supervisor (lazo algebraico)
add_block('simulink/Discrete/Unit Delay', [mdl '/Onboard Status z-1'], 'SampleTime', '0.01', ...
    'InitialCondition', '[0; 0; 0; 0]', 'Position', [1720 1255 1750 1285]);
from_en(mdl, [mdl '/Onboard Status z-1'], 1, 'ONBOARD_RAW');
goto_en(mdl, [mdl '/Onboard Status z-1'], 1, 'ONBOARD');
% loopback y Communication Status por dron desde los Demux (alineados con
% las entradas 4-7 del MPC LINK CHECK)
ph = get_param(L.enl, 'PortHandles');
dm = {'Demux LB', 'LB'; 'Demux CS', 'CS'};
for j = 1:2
    p1 = get_param(ph.Inport(2 + 2*j), 'Position');
    p2 = get_param(ph.Inport(3 + 2*j), 'Position');
    set_param([mdl '/' dm{j,1}], 'Position', [1360 p1(2)-10 1365 p2(2)+10]);
    from_en(mdl, [mdl '/' dm{j,1}], 1, dm{j,2});
    add_line(mdl, [dm{j,1} '/1'], sprintf('MPC LINK CHECK/%d', 2 + 2*j), 'autorouting', 'on');
    add_line(mdl, [dm{j,1} '/2'], sprintf('MPC LINK CHECK/%d', 3 + 2*j), 'autorouting', 'on');
end
add_block('simulink/Sinks/Display', [mdl '/Onboard Status'], 'Position', [1720 1320 1800 1370]);
from_en(mdl, [mdl '/Onboard Status'], 1, 'ONBOARD');
nota(mdl, [900 1440 1890 1470], sprintf(['Falla a bordo (MPC): MPC LINK CHECK -> Onboard Status [fsm1 fsm2 cod1 cod2] -> MISSION SUPERVISOR. ' ...
    'FSM 7/8/9 o enlace perdido en vuelo -> alerta 9:\nel sano se aparta >= d_min_h a su altura, regresa y aterriza. ' ...
    'Escenarios: QD2_SIM.falla_fsm / falla_apilado / proto_mal / comm_off + resp_off.']), 9, 'left');
% parámetros de máscara de los bloques de la librería
f = fieldnames(L);
for k = 1:numel(f)
    fijar_mascara(L.(f{k}));
end
set_param(L.rl2, 'dron', '2');

% ================ 4. Python bridge, estación y detector ====================
area(mdl, '4. Python Bridge (Stream Server :18700) + simulated station and detector (50 Hz)', [40 460 700 900]);
b = [mdl '/SIMULATED DETECTOR'];
crear_detector(b, [300 500 520 600]);
from_en(mdl, b, 1, 'X1'); from_en(mdl, b, 2, 'X2'); from_en(mdl, b, 3, 'TEL');
goto_en(mdl, b, 1, 'TARGETS');
b = [mdl '/PYTHON BRIDGE'];
crear_puente(b, [300 680 520 820]);
from_en(mdl, b, 1, 'TEL'); from_en(mdl, b, 2, 'TARGETS'); from_en(mdl, b, 3, 'SOURCE'); from_en(mdl, b, 4, 'T');
goto_en(mdl, b, 1, 'PY');
add_block('simulink/Sinks/Display', [mdl '/Python connected'], 'Position', [600 735 660 765]);
add_line(mdl, 'PYTHON BRIDGE/2', 'Python connected/1', 'autorouting', 'on');

% ================ 5. Scopes y registro ======================================
area(mdl, '5. Scopes & Logging', [40 950 700 1240]);
crear_scopes(mdl);
% fin de misión (sim)
b = [mdl '/MISSION END (sim)'];
crear_mf(b, [1450 40 1670 90], codigo_fin_sim(), {'parar', '1'}, {'QD2_SIM'}, '0.01');
from_en(mdl, b, 1, 'MSTATE');
add_block('simulink/Sinks/Stop Simulation', [mdl '/Stop Simulation'], 'Position', [1710 50 1740 80]);
add_line(mdl, 'MISSION END (sim)/1', 'Stop Simulation/1');

% Verificación
info.actualizado = false;
try
    set_param(mdl, 'SimulationCommand', 'update');
    info.actualizado = true;
    fprintf('[sim] update diagram OK\n');
catch e
    info.error_update = getReport(e, 'basic');
    fprintf(2, '[sim] update diagram FALLÓ:\n%s\n', info.error_update);
end
save_system(mdl, archivo);
info.archivo = archivo;
fprintf('[sim] guardado %s\n', archivo);
end

% #########################################################################
function s = codigo_rutas()
s = sprintf([ ...
    '%% QD2_Sim_Dual: rutas de lib/ (funciones qd2_* y QD2_Mission_Lib) y sim/\n' ...
    'qd2_d = fileparts(get_param(bdroot, ''FileName''));\n' ...
    'for qd2_k = 1:4\n' ...
    '    if exist(fullfile(qd2_d, ''lib'', ''qd2_params.m''), ''file''), break; end\n' ...
    '    qd2_d = fileparts(qd2_d);\n' ...
    'end\n' ...
    'addpath(fullfile(qd2_d, ''lib''));\n' ...
    'addpath(fullfile(qd2_d, ''sim''));\n' ...
    'clear qd2_d qd2_k\n']);
end

function s = codigo_preload()
% PreLoadFcn: el modelo aún no está cargado (no hay bdroot), así que se
% busca lib/ a partir de la carpeta actual y de which('QD2_Sim_Dual').
% Así los enlaces a QD2_Mission_Lib se resuelven al abrirlo con doble clic.
s = sprintf([ ...
    '%% QD2_Sim_Dual: agrega lib/ y sim/ al path antes de cargar (enlaces a QD2_Mission_Lib)\n' ...
    'qd2_c = {pwd};\n' ...
    'qd2_w = which(''QD2_Sim_Dual'');\n' ...
    'if ~isempty(qd2_w), qd2_c{end+1} = fileparts(qd2_w); end\n' ...
    'for qd2_i = 1:numel(qd2_c)\n' ...
    '    qd2_d = qd2_c{qd2_i};\n' ...
    '    for qd2_k = 1:4\n' ...
    '        if exist(fullfile(qd2_d, ''lib'', ''QD2_Mission_Lib.slx''), ''file'')\n' ...
    '            addpath(fullfile(qd2_d, ''lib''));\n' ...
    '            addpath(fullfile(qd2_d, ''sim''));\n' ...
    '            break;\n' ...
    '        end\n' ...
    '        qd2_d = fileparts(qd2_d);\n' ...
    '    end\n' ...
    'end\n' ...
    'clear qd2_c qd2_w qd2_i qd2_d qd2_k\n']);
end

function s = codigo_initfcn()
s = [codigo_rutas() sprintf([ ...
    '%% Parámetros (config/estacion.json es la única fuente de verdad)\n' ...
    'QD2P = qd2_params_from_config();\n' ...
    'QD2_SIM = qd2_sim_parametros();\n' ...
    '%% La versión la fija el bloque constante VERSION de la raíz\n' ...
    'QD2_VERSION = str2double(get_param([bdroot ''/'' sprintf(''VERSION\\n(1 = PID, 2 = MPC)'')], ''Value''));\n'])];
end

% #########################################################################
function b = lib_blk(mdl, lib, nombre, pos, tin, tout, nombre_local)
if nargin < 7, nombre_local = nombre; end
b = [mdl '/' nombre_local];
add_block([lib '/' nombre], b, 'Position', pos);
ph = get_param(b, 'PortHandles');
assert(numel(ph.Inport) == numel(tin) && numel(ph.Outport) == numel(tout), ...
    'La interfaz de %s cambió en QD2_Mission_Lib (%d/%d puertos)', nombre, numel(ph.Inport), numel(ph.Outport));
for k = 1:numel(tin)
    if ~isempty(tin{k}), from_en(mdl, b, k, tin{k}); end
end
for k = 1:numel(tout)
    if isempty(tout{k})
        pp = get_param(ph.Outport(k), 'Position');
        t = add_block('simulink/Sinks/Terminator', [mdl '/Term ' nombre_local], 'MakeNameUnique', 'on', ...
            'Position', [pp(1)+30 pp(2)-8 pp(1)+46 pp(2)+8], 'ShowName', 'off');
        pt = get_param(t, 'PortHandles');
        add_line(mdl, ph.Outport(k), pt.Inport(1));
    else
        goto_en(mdl, b, k, tout{k});
    end
end
end

function fijar_mascara(b)
mv = get_param(b, 'MaskNames');
if any(strcmp(mv, 'P')), set_param(b, 'P', 'QD2P'); end
if any(strcmp(mv, 'version')), set_param(b, 'version', 'QD2_VERSION'); end
if any(strcmp(mv, 'Ts')), set_param(b, 'Ts', '0.01'); end
end

function from_en(sys, b, k, tag)
ph = get_param(b, 'PortHandles');
pp = get_param(ph.Inport(k), 'Position');
f = add_block('simulink/Signal Routing/From', [sys '/From'], 'MakeNameUnique', 'on', 'GotoTag', tag, ...
    'Position', [pp(1)-150 pp(2)-7 pp(1)-40 pp(2)+7], 'ShowName', 'off');
pf = get_param(f, 'PortHandles');
add_line(sys, pf.Outport(1), ph.Inport(k));
end

function goto_en(sys, b, k, tag)
ph = get_param(b, 'PortHandles');
pp = get_param(ph.Outport(k), 'Position');
g = add_block('simulink/Signal Routing/Goto', [sys '/Goto'], 'MakeNameUnique', 'on', 'GotoTag', tag, ...
    'Position', [pp(1)+40 pp(2)-7 pp(1)+150 pp(2)+7], 'ShowName', 'off');
pg = get_param(g, 'PortHandles');
add_line(sys, ph.Outport(k), pg.Inport(1));
end

function h = crear_mf(b, pos, codigo, tam, params, ts, color)
if nargin < 7, color = 'white'; end
add_block('simulink/User-Defined Functions/MATLAB Function', b, 'Position', pos, 'BackgroundColor', color);
rt = sfroot;
ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', b);
ch.Script = codigo;
ch.SampleTime = ts;
for k = 1:numel(params)
    d = ch.find('-isa', 'Stateflow.Data', 'Name', params{k});
    d.Scope = 'Parameter';
    d.Tunable = false;
end
for j = 1:size(tam, 1)
    dd = ch.find('-isa', 'Stateflow.Data', 'Name', tam{j,1});
    dd.Props.Array.Size = tam{j,2};
end
h = get_param(b, 'Handle');
end

function sub = nuevo_subsistema(b, pos, ent, sal, color)
add_block('simulink/Ports & Subsystems/Subsystem', b, 'Position', pos, 'BackgroundColor', color);
delete_line(b, 'In1/1', 'Out1/1');
delete_block([b '/In1']);
delete_block([b '/Out1']);
for i = 1:numel(ent)
