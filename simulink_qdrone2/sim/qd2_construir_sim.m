function s = codigo_link()
s = sprintf([ ...
'function [tel1, tel2, lb, cs] = fcn(t, s1, s2, QD2_SIM)\n' ...
'%%#codegen\n' ...
'%% DRONE LINK (sim): respuesta de 8 doubles de cada dron como la manda\n' ...
'%% QD2_DroneStack_MPC (ARQUITECTURA §3.2): [eco ts, FSM, batería, estado MPC, T,\n' ...
'%% roll, pitch, 2 = etiqueta protocolo MPC v1]. s1/s2 = Onboard Status [FSM bat est T comm].\n' ...
'%% QD2_SIM.proto_mal [dron t1 t2]: ese dron responde sin la etiqueta (0) en [t1, t2).\n' ...
'%% QD2_SIM.resp_off [dron t1 t2]: la respuesta dron->PC no llega en [t1, t2): el Stream\n' ...
'%% Server ("most recent") retiene la última y el loopback crece (lb = t - eco retenido).\n' ...
'%% lb = loopback (0: el enlace simulado no tiene latencia); cs = Communication Status\n' ...
'%% (1 si el dron perdió el enlace PC->dron, QD2_SIM.comm_off).\n' ...
'persistent u1 u2\n' ...
'if isempty(u1)\n' ...
'    u1 = [0; NaN(7, 1)];\n' ...
'    u2 = [0; NaN(7, 1)];\n' ...
'end\n' ...
'tg = [2 2];\n' ...
'pm = QD2_SIM.proto_mal;\n' ...
'for k = 1:size(pm, 1)\n' ...
'    if pm(k,1) >= 1 && pm(k,1) <= 2 && t >= pm(k,2) && t < pm(k,3)\n' ...
'        tg(pm(k,1)) = 0;\n' ...
'    end\n' ...
'end\n' ...
'perd = [false false];\n' ...
'ro = QD2_SIM.resp_off;\n' ...
'for k = 1:size(ro, 1)\n' ...
'    if ro(k,1) >= 1 && ro(k,1) <= 2 && t >= ro(k,2) && t < ro(k,3)\n' ...
'        perd(ro(k,1)) = true;\n' ...
'    end\n' ...
'end\n' ...
'lb = [0; 0];\n' ...
'if ~perd(1)\n' ...
'    u1 = [t; s1(1); s1(2); s1(3); s1(4); 0; 0; tg(1)];\n' ...
'else\n' ...
'    lb(1) = t - u1(1);\n' ...
'end\n' ...
'if ~perd(2)\n' ...
'    u2 = [t; s2(1); s2(2); s2(3); s2(4); 0; 0; tg(2)];\n' ...
'else\n' ...
'    lb(2) = t - u2(1);\n' ...
'end\n' ...
'tel1 = u1;\n' ...
'tel2 = u2;\n' ...
'cs = [s1(5); s2(5)];\n']);
end

